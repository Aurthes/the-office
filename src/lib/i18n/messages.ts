const ENGLISH = new Map(Object.entries(ZH_CN).map(([en, zh]) => [zh, en]));
ENGLISH.set("无效的会话", "Invalid session");
export type UiTranslator = (text: string, values?: Record<string, string | number>) => string;

export function translateUi(text: string, language: "en" | "zh-CN" = "en", values?: Record<string, string | number>): string {
  const english = ENGLISH.get(text) ?? text;
  const message = language === "zh-CN" && Object.hasOwn(ZH_CN, english) ? ZH_CN[english] : english;
  return message.replace(/\{(\w+)\}/g, (placeholder, key: string) => values?.[key] === undefined ? placeholder : String(values[key]));
}
